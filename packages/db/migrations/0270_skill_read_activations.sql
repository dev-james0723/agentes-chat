CREATE TABLE "skill_read_activations" (
	"id" uuid PRIMARY KEY NOT NULL,
	"org_id" uuid NOT NULL,
	"agent_id" uuid NOT NULL,
	"run_id" uuid NOT NULL,
	"server_step_id" uuid NOT NULL,
	"tool_use_id" text NOT NULL,
	"binding_hash" text NOT NULL,
	"skill_id" uuid NOT NULL,
	"skill_version" integer NOT NULL,
	"content_hash" text NOT NULL,
	"purpose_hash" text NOT NULL,
	"source_proof_hash" text NOT NULL,
	"surface_hash" text NOT NULL,
	"envelope" jsonb NOT NULL,
	"issued_at" timestamp with time zone NOT NULL,
	"expires_at" timestamp with time zone NOT NULL,
	"revoked_at" timestamp with time zone,
	"used_count" integer DEFAULT 0 NOT NULL,
	"state" text DEFAULT 'issued' NOT NULL,
	"completed_at" timestamp with time zone,
	"result_hash" text,
	CONSTRAINT "skill_read_activations_orgId_runId_toolUseId_unique" UNIQUE("org_id","run_id","tool_use_id"),
	CONSTRAINT "skill_read_activations_expiry" CHECK ("skill_read_activations"."expires_at" > "skill_read_activations"."issued_at" and "skill_read_activations"."expires_at" <= "skill_read_activations"."issued_at" + interval '5 minutes'),
	CONSTRAINT "skill_read_activations_used_count" CHECK ("skill_read_activations"."used_count" in (0, 1)),
	CONSTRAINT "skill_read_activations_skill_version" CHECK ("skill_read_activations"."skill_version" > 0),
	CONSTRAINT "skill_read_activations_state" CHECK (("skill_read_activations"."state" = 'issued' and "skill_read_activations"."used_count" = 0 and "skill_read_activations"."completed_at" is null and "skill_read_activations"."result_hash" is null)
        or ("skill_read_activations"."state" = 'completed' and "skill_read_activations"."used_count" = 1 and "skill_read_activations"."completed_at" is not null and "skill_read_activations"."result_hash" = "skill_read_activations"."content_hash"))
);
